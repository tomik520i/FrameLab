"""Generate native language metadata from the shared worker catalog."""
from pathlib import Path
import json
root=Path(__file__).resolve().parents[1]
data=json.loads((root/'docs/subtitle-languages.json').read_text('utf-8'))['languages']
quote=lambda s: json.dumps(s,ensure_ascii=False)
lines=['// Generated by tools/generate_subtitle_languages.py; edit docs/subtitle-languages.json.',
       '#pragma once','#include <array>','#include <string_view>',
       'struct SubtitleLanguage {const char* code;const char* name;const char* cs;const char* ocr;const wchar_t* windows;bool rtl;};',
       f'inline constexpr std::array<SubtitleLanguage,{len(data)}> subtitleLanguages{{{{']
for x in data:
    lines.append(' {'+','.join([quote(x['code']),quote(x['name']),quote(x['name_cs']),quote(x['ocr_model']),'L'+quote(x['windows']),'true' if x['rtl'] else 'false'])+'},')
lines+=['}};', 'inline const SubtitleLanguage* subtitleLanguage(std::string_view code){for(const auto& x:subtitleLanguages)if(code==x.code)return &x;return nullptr;}',
        'inline bool subtitlePairSupported(int model,std::string_view source,std::string_view target){return subtitleLanguage(source)&&subtitleLanguage(target)&&source!=target&&(model>=4||(source=="en"&&target=="cs"));}']
(root/'src/SubtitleLanguages.hpp').write_text('\n'.join(lines)+'\n','utf-8')
